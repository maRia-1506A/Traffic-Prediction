export function buildOfficialRoutes() {
  return OFFICIAL_ROUTES_RAW.map(item => {
    const nodeNames = item.path.split("->").map(s => s.trim()).filter(Boolean);
    const waypoints = nodeNames.map(name => {
      const coords = NODE_COORDINATES[name] || [23.8069, 90.3687];
      return { name, coords };
    });

    const originName = waypoints[0]?.name || "Origin";
    const destName = waypoints[waypoints.length - 1]?.name || "Destination";
    const originCoords = waypoints[0]?.coords || [23.8103, 90.4125];
    const destCoords = waypoints[waypoints.length - 1]?.coords || [23.8103, 90.4125];

    let totalDist = 0;
    for (let i = 0; i < waypoints.length - 1; i++) {
      totalDist += haversineKm(waypoints[i].coords, waypoints[i + 1].coords);
    }
    totalDist = Math.max(Number(totalDist.toFixed(2)), 1.5);
    const freeFlowTimeMin = Math.max(2.0, Number(((totalDist / 38.0) * 60).toFixed(1)));

    return {
      route_code: item.id,
      route_id: `${item.id}: ${originName} -> ${destName}`,
      route_path: item.path,
      origin_name: originName,
      dest_name: destName,
      origin_coords: originCoords,
      dest_coords: destCoords,
      waypoints,
      road_length_km: totalDist,
      free_flow_time_min: freeFlowTimeMin,
      road_type: totalDist > 15 ? "Trunk / Highway" : totalDist > 7 ? "Primary Arterial" : "Secondary Urban",
      num_lanes: 4
    };
  });
}

